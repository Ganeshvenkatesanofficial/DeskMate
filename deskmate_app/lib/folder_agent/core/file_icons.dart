/// djb2 hash of the folder name → deterministic scoop (matches FilDOS).
int folderScoopIndex(String name) {
  var h = 5381;
  for (final c in name.codeUnits) {
    h = (((h << 5) + h) ^ c) & 0xFFFFFFFF;
  }
  return h % _folderScoops.length;
}

String folderIconAsset(String name) =>
    '$_base/${_folderScoops[folderScoopIndex(name)]}.svg';

/// Asset path of the icon for a file or folder.
String fileIconAsset({required String name, required bool isDir, String ext = ''}) {
  if (isDir) return folderIconAsset(name);
  final lower = name.toLowerCase();
  if (lower == '.env' || lower.startsWith('.env.')) return '$_base/env-secrets.svg';
  final byName = _byName[lower];
  if (byName != null) return '$_base/$byName.svg';
  if (ext.isNotEmpty) return '$_base/${_byExt[ext.toLowerCase()] ?? 'others'}.svg';
  return '$_base/unknown.svg';
}
